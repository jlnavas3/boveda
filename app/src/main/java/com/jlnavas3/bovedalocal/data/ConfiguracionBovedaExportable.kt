            prefijoNumeroOculto = config.comunicacionesPrefijoNumeroOculto ?: this.comunicaciones.prefijoNumeroOculto,
            habilitarLlamadaOculta = config.comunicacionesHabilitarLlamadaOculta ?: this.comunicaciones.habilitarLlamadaOculta,
            habilitarWhatsappDirecto = config.comunicacionesHabilitarWhatsappDirecto ?: this.comunicaciones.habilitarWhatsappDirecto,
            paisPredeterminadoTelefono = config.comunicacionesPaisPredeterminadoTelefono ?: this.comunicaciones.paisPredeterminadoTelefono,
            modoEnvioMensajeSeguro = config.comunicacionesModoEnvioMensajeSeguro ?: this.comunicaciones.modoEnvioMensajeSeguro,
            preguntarPurgaAgenda = config.comunicacionesPreguntarPurgaAgenda ?: this.comunicaciones.preguntarPurgaAgenda
        )
    )
}
